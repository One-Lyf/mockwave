import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import kitdemo from '../../../stacks/kitdemo/schema.json';
import type { KitSchema } from './schema';
import { schemaToHardeningSql, schemaToSql } from './sql';

const schema = kitdemo as KitSchema;
const MIGRATIONS = join(dirname(fileURLToPath(import.meta.url)), '../../../stacks/kitdemo/migrations');
const MIGRATION = join(MIGRATIONS, '0001_kitdemo_init.sql');
const HARDENING = join(MIGRATIONS, '0002_kitdemo_bounds.sql');

describe('schemaToSql', () => {
  it('matches the committed kitdemo migration (run `npm run gen:sql` to refresh)', () => {
    // 0001 is applied and never edited: it is the original, unbounded shape (bounds: false).
    const sql = schemaToSql('kitdemo', schema, { bounds: false });
    // The committed migration keeps the header it was applied with (applied migrations are
    // never edited), so compare the SQL body below the generated-by line.
    const body = (s: string) => s.replace(/^-- Generated by [^\n]*\n/, '');
    if (process.env.UPDATE_SQL) {
      // gen:sql refreshes only the body; the applied migration's header line stays untouched.
      const current = readFileSync(MIGRATION, 'utf8');
      const header = current.match(/^-- Generated by [^\n]*\n/);
      writeFileSync(MIGRATION, (header ? header[0] : '') + body(sql));
    }
    expect(body(readFileSync(MIGRATION, 'utf8'))).toBe(body(sql));
  });

  it('matches the committed 0002 hardening migration (run `npm run gen:sql` to refresh)', () => {
    const sql = schemaToHardeningSql('kitdemo', schema);
    if (process.env.UPDATE_SQL) writeFileSync(HARDENING, sql);
    expect(readFileSync(HARDENING, 'utf8')).toBe(sql);
  });

  it('bounds every string column (F4): default 1000, per-field maxLength, none on other types', () => {
    const sql = schemaToSql('kitdemo', schema);
    expect(sql).toContain(`"name" text not null check (char_length("name") <= 200)`);
    expect(sql).toContain(`"note" text check (char_length("note") <= 1000)`);
    expect(sql).not.toMatch(/"kcal" double precision[^,\n]*char_length/);
    // Every `text` column that is a free string carries a length check; enums are bounded by their value list.
    for (const line of sql.split('\n').filter((l) => /^ {2}"\w+" text\b/.test(l) && !l.includes(' in ('))) {
      expect(line).toMatch(/char_length\("\w+"\) <= \d+/);
    }
  });

  it('caps rows per owner with a locked insert trigger (F4)', () => {
    const sql = schemaToSql('kitdemo', schema, { maxRowsPerOwner: 42 });
    for (const t of ['food', 'meal', 'goal']) {
      expect(sql).toContain(`create trigger row_cap before insert on "kitdemo"."${t}"`);
    }
    expect(sql).toContain('if n < 42 then');
    expect(sql).toContain('pg_advisory_xact_lock');
    // H-N1: PostgREST custom error (HTTP 400), invoker rights, empty search_path; never a plain 54000 (HTTP 500).
    expect(sql).toContain(`raise sqlstate 'PGRST'`);
    expect(sql).toContain(`'status', 400`);
    expect(sql).toContain(`'code', '54000'`);
    expect(sql).toContain(`set search_path = ''`);
    expect(sql).not.toMatch(/security definer|errcode = '54000'/);
    expect(schemaToSql('kitdemo', schema)).toContain('if n < 5000 then');
    expect(schemaToSql('kitdemo', schema, { bounds: false })).not.toMatch(/row_cap|char_length/);
    expect(() => schemaToSql('kitdemo', schema, { maxRowsPerOwner: 0 })).toThrow('maxRowsPerOwner');
  });

  it('rejects a bad maxLength and puts constraints in the hardening migration idempotently', () => {
    const bad = (f: object) => schemaToSql('x', { entities: [{ name: 'a', scope: 'user', fields: [f as never] }] });
    expect(() => bad({ name: 'k', type: 'number', maxLength: 5 })).toThrow('maxLength');
    expect(() => bad({ name: 'k', type: 'string', maxLength: 0 })).toThrow('maxLength');
    const sql = schemaToHardeningSql('kitdemo', schema);
    expect(sql).toContain('drop constraint if exists "food_name_len"');
    expect(sql).toContain('check (char_length("name") <= 200) not valid');
    expect(sql).toContain('drop trigger if exists row_cap');
  });

  it('refuses bad slugs, invalid schemas and household scope', () => {
    expect(() => schemaToSql('Kit-Demo', schema)).toThrow('app slug');
    expect(() => schemaToSql('x', { entities: [{ name: 'a', scope: 'user', fields: [{ name: 'ownerId', type: 'string' }] }] })).toThrow(
      'reserved name',
    );
    expect(() => schemaToSql('x', { entities: [{ name: 'chore', scope: 'household', fields: [] }] })).toThrow('household');
  });

  it('quotes the app schema, so a reserved word is a valid slug', () => {
    const sql = schemaToSql('user', { entities: [{ name: 'a', scope: 'user', fields: [] }] });
    expect(sql).toContain('create schema if not exists "user";');
    expect(sql).toContain('create table "user"."a" (');
  });

  it('escapes quotes in enum values', () => {
    const sql = schemaToSql('x', { entities: [{ name: 'a', scope: 'user', fields: [{ name: 'k', type: 'enum', enum: ["it's"] }] }] });
    expect(sql).toContain(`'it''s'`);
  });
});

// Owner scoping, tested with two users against a real Postgres. The stack's `auth.uid()` reads the
// JWT claims PostgREST sets per request; here the same setting is set by hand. Skipped without Postgres.
const pgBin = ['/usr/lib/postgresql'].filter(existsSync).flatMap((d) => readdirSync(d).map((v) => join(d, v, 'bin')))[0];
const asRoot = process.getuid?.() === 0;

describe.skipIf(!pgBin)('owner scoping on the kitdemo migration (two users)', () => {
  let dir = '';
  const port = String(55000 + Math.floor(Math.random() * 1000));
  const run = (bin: string, args: string[]) =>
    execFileSync(asRoot ? 'runuser' : join(pgBin!, bin), asRoot ? ['-u', 'postgres', '--', join(pgBin!, bin), ...args] : args, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  const psql = (sql: string) => run('psql', ['-h', dir, '-p', port, '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-qAt', '-c', sql]).trim();

  const A = '00000000-0000-0000-0000-00000000000a';
  const B = '00000000-0000-0000-0000-00000000000b';
  const as = (sub: string, sql: string) =>
    psql(
      `begin; set local role authenticated; set local "request.jwt.claims" = '{"sub":"${sub}","role":"authenticated"}'; ${sql}; commit;`,
    );
  const fails = (sub: string, sql: string) => {
    try {
      as(sub, sql);
    } catch (e) {
      return String((e as { stderr?: string }).stderr ?? e);
    }
    throw new Error(`expected failure: ${sql}`);
  };
  const now = `'2026-10-05T12:00:00Z'`;
  const food = (id: string, name: string, extra = '') =>
    `insert into kitdemo.food (id, "createdAt", "updatedAt", name, kcal${extra ? ', "ownerId"' : ''}) values ('${id}', ${now}, ${now}, '${name}', 100${extra ? `, '${extra}'` : ''})`;
  const fA = '10000000-0000-0000-0000-00000000000a';
  const fB = '10000000-0000-0000-0000-00000000000b';

  beforeAll(() => {
    dir = mkdtempSync(join(tmpdir(), 'kitpg-'));
    if (asRoot) execFileSync('chown', ['postgres', dir]);
    run('initdb', ['-D', join(dir, 'data'), '-U', 'postgres', '-A', 'trust']);
    run('pg_ctl', ['-D', join(dir, 'data'), '-l', join(dir, 'log'), '-o', `-k ${dir} -p ${port} -c listen_addresses=''`, '-w', 'start']);
    // What the W2 app stack provides: the API roles, and auth.uid() with the same body as
    // citadel infra/stacks/templates/db/auth-helpers.sql (reads request.jwt.claims, as PostgREST v14 sets it).
    psql(`create role anon nologin; create role authenticated nologin; create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
          (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'))::uuid $$;
      grant usage on schema auth to anon, authenticated;`);
    psql(readFileSync(MIGRATION, 'utf8'));
    psql(readFileSync(HARDENING, 'utf8'));
    psql(readFileSync(HARDENING, 'utf8')); // idempotent
    as(A, food(fA, 'Oats'));
    as(B, food(fB, 'Rice'));
  }, 60_000);

  afterAll(() => {
    if (!dir) return;
    try {
      run('pg_ctl', ['-D', join(dir, 'data'), '-m', 'immediate', 'stop']);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('stamps the owner and shows each user only their own rows', () => {
    expect(as(A, `select name, "ownerId" from kitdemo.food`)).toBe(`Oats|${A}`);
    expect(as(B, `select name from kitdemo.food`)).toBe('Rice');
  });

  it("does not let one user change or delete another's rows", () => {
    expect(as(B, `update kitdemo.food set kcal = 1 where id = '${fA}' returning id`)).toBe('');
    expect(as(B, `delete from kitdemo.food where id = '${fA}' returning id`)).toBe('');
    expect(as(A, `select kcal from kitdemo.food`)).toBe('100');
  });

  it('refuses rows written for another owner, including through upsert', () => {
    expect(fails(B, food('10000000-0000-0000-0000-0000000000bb', 'Fake', A))).toMatch(/row-level security/);
    expect(fails(B, `${food(fA, 'Stolen')} on conflict (id) do update set name = excluded.name`)).toMatch(/row-level security/);
  });

  it("refuses a ref to another user's row", () => {
    const meal = (sub: string, f: string) =>
      as(sub, `insert into kitdemo.meal (id, "createdAt", "updatedAt", food, kind, "eatenAt") values (gen_random_uuid(), ${now}, ${now}, '${f}', 'lunch', ${now})`);
    meal(A, fA);
    expect(() => meal(B, fA)).toThrow(/foreign key/);
  });

  it('enforces enum values and gives anon no access', () => {
    expect(
      fails(A, `insert into kitdemo.meal (id, "createdAt", "updatedAt", food, kind, "eatenAt") values (gen_random_uuid(), ${now}, ${now}, '${fA}', 'brunch', ${now})`),
    ).toMatch(/check constraint/);
    expect(() => psql(`set role anon; select * from kitdemo.food`)).toThrow(/permission denied/);
  });

  it('refuses oversize text and enforces the per-owner row cap, upserts of existing rows excepted (F4)', () => {
    const long = (n: number) => 'x'.repeat(n);
    expect(fails(A, food('10000000-0000-0000-0000-0000000000c1', long(201)))).toMatch(/food_name_len|check constraint/);
    as(A, food('10000000-0000-0000-0000-0000000000c2', long(200)));
    // Rebuild the triggers with a cap of 3 and fill user A's food table (already holds Oats + the 200-char row).
    psql(schemaToHardeningSql('kitdemo', schema, { maxRowsPerOwner: 3 }));
    as(A, food('10000000-0000-0000-0000-0000000000c3', 'Third'));
    // H-N1: the refusal is SQLSTATE PGRST (PostgREST answers HTTP 400 with code 54000), not a plain 54000 (HTTP 500).
    const refused = fails(A, food('10000000-0000-0000-0000-0000000000c4', 'Fourth'));
    expect(refused).toMatch(/row limit reached/);
    expect(refused).toMatch(/"code"\s*:\s*"54000"/);
    // Upsert of an existing row still works at the cap; another user is unaffected.
    as(A, `${food(fA, 'Oats2')} on conflict (id) do update set name = excluded.name`);
    as(B, food('10000000-0000-0000-0000-0000000000b2', 'Beans'));
  });
});
