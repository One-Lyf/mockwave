function generateMockFromSchema(schema: string): string {
  // Simple heuristic: if it looks like TypeScript, generate TypeScript mock
  if (schema.includes('interface') || schema.includes('type ')) {
    return `// Auto-generated mock data from your schema
// Mockwave - deterministic mock generation

${generateTypeScriptMock(schema)}`;
  }
  // If it looks like JSON, generate JSON mock
  if (schema.trim().startsWith('{') || schema.trim().startsWith('[')) {
    return generateJSONMock(schema);
  }
  // Default: wrap in a basic mock structure
  return `// Mockwave generated mock
// TODO: Implement based on your schema
{
  id: 'mock-' + Math.random().toString(36).substring(2, 9),
  name: 'Mock Item',
  value: 42,
  isActive: true,
  createdAt: new Date().toISOString(),
}`;
}

function generateTypeScriptMock(schema: string): string {
  // Extract interface name for better output
  const interfaceMatch = schema.match(/interface\s+(\w+)/);
  const typeName = interfaceMatch ? interfaceMatch[1] : 'Mock';
  
  return `export const mock${typeName}: ${typeName} = {
  id: crypto.randomUUID(),
  name: 'Mock ${typeName}',
  description: 'Generated by Mockwave',
  // ... other fields will be populated based on your schema
};

export const mock${typeName}List: ${typeName}[] = Array(10).fill(null).map(() => mock${typeName});`;
}

function generateJSONMock(schema: string): string {
  return `{
  "mockData": {
    "generatedAt": "${new Date().toISOString()}",
    "sourceSchema": "Your schema here",
    "items": [
      { "id": 1, "name": "Mock Item 1", "value": 42 },
      { "id": 2, "name": "Mock Item 2", "value": 84 },
      { "id": 3, "name": "Mock Item 3", "value": 126 }
    ]
  }
}`;
}
